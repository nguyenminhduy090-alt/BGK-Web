        ON DELETE RESTRICT,                               -- khong cho xoa loai con mon dung
    CONSTRAINT "UQ_Dish_Name_PerCategory"
        UNIQUE ("BIT240082_DishCategoryId", "BIT240082_Name")  -- ten mon khong trung trong cung 1 loai
