DROP TABLE IF EXISTS "BIT240082_DishImages" CASCADE;
DROP TABLE IF EXISTS "BIT240082_Dishes" CASCADE;
DROP TABLE IF EXISTS "BIT240082_DishCategories" CASCADE;

CREATE TABLE "BIT240082_DishCategories" (
    "BIT240082_Id"          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BIT240082_Name"        VARCHAR(100) NOT NULL,
    "BIT240082_Description" VARCHAR(500) NULL
);

CREATE TABLE "BIT240082_Dishes" (
    "BIT240082_Id"               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BIT240082_Name"             VARCHAR(150) NOT NULL,
    "BIT240082_Price"            NUMERIC(18,2) NOT NULL CHECK ("BIT240082_Price" > 0),
    "BIT240082_PreparationTime"  INTEGER NOT NULL CHECK ("BIT240082_PreparationTime" > 0),
    "BIT240082_IsAvailable"      BOOLEAN NOT NULL DEFAULT TRUE,
    "BIT240082_Description"      VARCHAR(1000) NULL,
    "BIT240082_DishCategoryId"   INTEGER NOT NULL,
    CONSTRAINT "FK_Dishes_DishCategories"
        FOREIGN KEY ("BIT240082_DishCategoryId")
        REFERENCES "BIT240082_DishCategories" ("BIT240082_Id")
        ON DELETE RESTRICT,
    CONSTRAINT "UQ_Dish_Name_PerCategory"
        UNIQUE ("BIT240082_DishCategoryId", "BIT240082_Name")
);

CREATE TABLE "BIT240082_DishImages" (
    "BIT240082_Id"          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BIT240082_ImageUrl"    VARCHAR(500) NOT NULL,
    "BIT240082_IsThumbnail" BOOLEAN NOT NULL DEFAULT FALSE,
    "BIT240082_DishId"      INTEGER NOT NULL,
    CONSTRAINT "FK_DishImages_Dishes"
        FOREIGN KEY ("BIT240082_DishId")
        REFERENCES "BIT240082_Dishes" ("BIT240082_Id")
        ON DELETE CASCADE
);

